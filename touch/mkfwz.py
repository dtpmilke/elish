#!/usr/bin/env python3
"""Create the NT36523 firmware header from a local elish firmware directory."""
import argparse
import hashlib
import struct
from pathlib import Path

FIRMWARE = (
    ("novatek_nt36523_k81a_fw01.bin", "33d2e0a9217df7e898a96728631f3b6decd85ddb7d4112b38b9d7d6d162d6938"),
    ("novatek_nt36523_k81a_fw02.bin", "f38633bf75ca75d735785fe3e802f9b89fb4a25aaeb8783b450c24cb333cfcf1"),
)


def pack(data):
    packed = bytearray()
    literal_start = 0
    cursor = 0
    while cursor < len(data):
        end = cursor
        while end < len(data) and data[end] == 0:
            end += 1
        if end - cursor >= 32 or end == len(data):
            packed += struct.pack("<I", cursor - literal_start)
            packed += data[literal_start:cursor]
            packed += struct.pack("<I", end - cursor)
            literal_start = end
        cursor = max(end, cursor + 1)
    if literal_start < len(data):
        packed += struct.pack("<I", len(data) - literal_start)
        packed += data[literal_start:]
        packed += struct.pack("<I", 0)
    return packed


def generate(firmware_dir, output):
    arrays = ["/* Generated by mkfwz.py from local firmware. */\n"]
    entries = []
    for index, (name, expected) in enumerate(FIRMWARE):
        data = (firmware_dir / name).read_bytes()
        if hashlib.sha256(data).hexdigest() != expected:
            raise ValueError(f"unexpected SHA-256 for {name}; expected {expected}")
        packed = pack(data)
        rows = ",\n".join(
            "  " + ", ".join(f"0x{byte:02x}" for byte in packed[start:start + 16])
            for start in range(0, len(packed), 16)
        )
        symbol = f"gNvtFwZ{index}"
        arrays.append(f"/* {name} */\nstatic const unsigned char {symbol}[{len(packed)}] = {{\n{rows}\n}};\n")
        entries.append(f'  {{ {symbol}, sizeof({symbol}), {len(data)}, "{name}" }},\n')

    with output.open("x", encoding="ascii", newline="\n") as header:
        header.writelines(arrays)
        header.write(
            "static const struct { const unsigned char *Z; unsigned long ZLen, Size; "
            "const char *Name; } gNvtFws[] = {\n"
        )
        header.writelines(entries)
        header.write("};\nstatic const volatile unsigned char gSizePad[1] = { 1 };\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("firmware_dir", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    try:
        generate(args.firmware_dir, args.output)
    except (OSError, ValueError) as exc:
        parser.exit(1, f"error: {exc}\n")
